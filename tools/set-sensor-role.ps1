param(
    [Parameter(Mandatory = $true)]
    [ValidateSet('disabled', 'sender', 'receiver')]
    [string]$Role
)

$repoRoot = Split-Path -Parent $PSScriptRoot
$overridePath = Join-Path $repoRoot 'sensor\include\override.h'

switch ($Role) {
    'disabled' {
        if (Test-Path $overridePath) {
            Remove-Item $overridePath -Force
            Write-Output "Sensor role override removed. Default mode is now disabled."
        }
        else {
            Write-Output "No role override present. Default mode is already disabled."
        }
        exit 0
    }
    'sender' {
        $modeMacro = 'SENSOR_MODE_ALARM_SEND'
    }
    'receiver' {
        $modeMacro = 'SENSOR_MODE_RECEIVE_ALARM'
    }
}

$content = @"
#pragma once

// Auto-generated by tools/set-sensor-role.ps1
#define SENSOR_MODE $modeMacro
"@

Set-Content -Path $overridePath -Value $content -Encoding UTF8
Write-Output "Sensor role set to $Role via $overridePath"
